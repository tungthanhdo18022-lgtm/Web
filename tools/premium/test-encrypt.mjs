/* ---------------- Tiny test harness ---------------- */
let passed = 0, failed = 0;
function ok(cond, msg, detail) {
  if (cond) { passed++; return true; }
  failed++;
  console.log('FAIL  ' + msg + (detail !== undefined ? '\n      ' + String(detail).slice(0, 600) : ''));
  return false;
}
function eq(actual, expected, msg) {
  try { assert.deepStrictEqual(actual, expected); passed++; return true; } catch (e) {
    failed++;
    console.log('FAIL  ' + msg + '\n      expected ' + JSON.stringify(expected).slice(0, 300) + '\n      actual   ' + JSON.stringify(actual).slice(0, 300));
    return false;
  }
}
function section(name) { console.log('--- ' + name); }


#!/usr/bin/env node
/*
 * End-to-end test of tools/premium/encrypt.mjs and tools/premium/decrypt.mjs.
 *
 *   PREMIUM_PRIVATE_KEY_FILE=/path/outside/the/repo/private-key.json node tools/premium/test-encrypt.mjs
 *   node tools/premium/test-encrypt.mjs --key /path/outside/the/repo/private-key.json [--keep]
 *
 * Copies tests/ and assets/ to temporary folders (the repository itself is never modified), adds a few
 * fixture tests, runs the tool there with --root, and checks with the PRIVATE key that every encrypted file
 * decrypts (Node crypto and WebCrypto) to exactly the original test, that the public metadata equals what the site
 * itself computes (assets/js/store.js loaded in a sandbox), and that the manifest, the other files, --check,
 * --dry-run, a second run, hidden / broken Advanced files, all-or-nothing writes and the private-key scan behave as
 * specified. It also checks that decrypt.mjs turns every encrypted file back into a test file that registers exactly
 * the original test (and re-encrypts to the same public data), and that it refuses to write inside the site.
 * The private key is only read from the given path; it is never printed or copied. Only Node built-ins are used.
 */

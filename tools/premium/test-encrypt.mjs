/* ---------------- Helpers ---------------- */
const quiet = { log() {}, info() {}, warn() {}, error() {}, debug() {} };

function walk(dir, base = dir, out = new Map()) {
  if (!fs.existsSync(dir)) return out;
  for (const name of fs.readdirSync(dir).sort()) {
    const abs = path.join(dir, name);
    const st = fs.statSync(abs);
    if (st.isDirectory()) walk(abs, base, out);
    else out.set(path.relative(base, abs).split(path.sep).join('/'), crypto.createHash('sha256').update(fs.readFileSync(abs)).digest('hex'));
  }
  return out;
}
function treeOf(root) { return new Map([...walk(path.join(root, 'tests'), root), ...walk(path.join(root, 'assets'), root)]); }
function sameTree(a, b) { return a.size === b.size && [...a].every(([k, v]) => b.get(k) === v); }
function diffTree(a, b) {
  const out = [];
  for (const [k, v] of a) if (!b.has(k)) out.push('-' + k); else if (b.get(k) !== v) out.push('~' + k);
  for (const k of b.keys()) if (!a.has(k)) out.push('+' + k);
  return out;
}

function runTool(root, ...args) {
  const r = spawnSync(process.execPath, [TOOL, '--root', root, ...args], { encoding: 'utf8' });
  return { status: r.status, stdout: r.stdout || '', stderr: r.stderr || '', out: (r.stdout || '') + (r.stderr || '') };
}

/** Runs decrypt.mjs with the private key in PREMIUM_PRIVATE_KEY_FILE (unless env overrides it). */
function runDecrypt(args, env = {}) {
  const r = spawnSync(process.execPath, [DECRYPT, ...args], {
    encoding: 'utf8', env: { ...process.env, PREMIUM_PRIVATE_KEY_FILE: keyFile, PREMIUM_PRIVATE_KEY: '', ...env }
  });
  return { status: r.status, stdout: r.stdout || '', stderr: r.stderr || '', out: (r.stdout || '') + (r.stderr || '') };
}

/** Extra temporary folders (removed at the end when everything passed). */
const extraTmp = [];
function tmpDir(prefix) {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  extraTmp.push(d);
  return d;
}

/** A small copy of the site: assets/ from the repository and the given files in tests/ (+ manifest). */
function miniSite(files, entries) {
  const root = tmpDir('premium-mini-');
  fs.cpSync(path.join(REPO, 'assets'), path.join(root, 'assets'), { recursive: true });
  fs.mkdirSync(path.join(root, 'tests'));
  for (const [name, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, 'tests', name)), { recursive: true });
    fs.writeFileSync(path.join(root, 'tests', name), text);
  }
  if (entries) fs.writeFileSync(path.join(root, 'tests/manifest.js'), loadAdminManifestText(REPO).manifestText(entries));
  return root;
}

function advText(id, title) {
  return "SATLibrary.register({\n  id: '" + id + "',\n  source: String.raw`\n---\ntitle: " + (title || 'Fixture ' + id) +
    "\nsection: advanced\n---\n\n1. Type 2\nAnswer: 2\n`\n});\n";
}

function allNames(dir, out = []) {
  for (const n of fs.readdirSync(dir)) {
    const a = path.join(dir, n);
    out.push(a);
    if (fs.lstatSync(a).isDirectory()) allNames(a, out);
  }
  return out;
}

/** Runs a test/stub file and captures what it registers. */
function capture(file) {
  const defs = [], stubs = [];
  const ctx = vm.createContext({ console: quiet, SATLibrary: { register: (d) => defs.push(d), registerPremium: (s) => stubs.push(s), manifest() {} } });
  vm.runInContext('var window = globalThis;', ctx);
  vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: file });
  return { defs, stubs };
}

/** Loads the site's own scripts (config, util, grading, parser, store) into a sandbox; returns the context. */
function loadSite(root) {
  const ctx = vm.createContext({ console: quiet });
  vm.runInContext(`var window = globalThis, self = globalThis;
    window.addEventListener = function () {}; window.removeEventListener = function () {};
    window.localStorage = { getItem: function () { return null; }, setItem: function () {}, removeItem: function () {} };
    window.U_STUB = { slug: function (s) { return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'test'; },
      lsGet: function (k, d) { return d; }, lsSet: function () { return true; }, lsDel: function () {}, uid: function (p) { return (p || '') + Math.random().toString(36).slice(2); } };`, ctx);
  const run = (rel) => vm.runInContext(fs.readFileSync(path.join(root, rel), 'utf8'), ctx, { filename: rel });
  run('assets/js/config.js');
  try { run('assets/js/util.js'); } catch (e) { /* util.js needs a DOM: use the stub */ }
  if (!ctx.U || typeof ctx.U.slug !== 'function') ctx.U = ctx.U_STUB;
  run('assets/js/grading.js');
  run('assets/js/parser.js');
  run('assets/js/store.js');
  if (!ctx.SATLibrary || typeof ctx.SATLibrary.register !== 'function') throw new Error('store.js did not define SATLibrary');
  return ctx;
}

/** Runs a plaintext test file through the real SATLibrary.register and returns the prepared test. */
function siteRegisterFile(site, file) {
  const before = new Set(site.SATLibrary.published().map((t) => t.id));
  vm.runInContext(fs.readFileSync(file, 'utf8'), site, { filename: file });
  const added = site.SATLibrary.published().filter((t) => !before.has(t.id));
  return added.length === 1 ? added[0] : null;
}

function metaOf(t) {
  const m = {};
  META.forEach((k) => { m[k] = k === 'category' || k === 'description' || k === 'title' ? String(t[k] || '') : t[k]; });
  m.moduleCount = t.modules ? t.modules.length : t.moduleCount;
  return m;
}

function loadAdminManifestText(root) {
  const ctx = vm.createContext({ console: quiet });
  vm.runInContext('var window = globalThis; window.U = {};', ctx);
  vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/admin.js'), 'utf8'), ctx, { filename: 'admin.js' });
  return { manifestText: ctx.Admin.manifestText, parseManifest: ctx.Admin.parseManifest };
}

function readManifest(root) {
  let entries = null;
  const ctx = vm.createContext({ SATLibrary: { manifest: (l) => { entries = Array.from(l).map((e) => ({ file: String(e.file), v: String(e.v) })); } } });
  vm.runInContext(fs.readFileSync(path.join(root, 'tests/manifest.js'), 'utf8'), ctx);
  return entries;
}

function bump(v) { return /^\d+$/.test(v) ? String(Number(v) + 1) : '1'; }

function decryptNode(stub) {
  const aesKey = crypto.privateDecrypt({ key: privateKey, padding: crypto.constants.RSA_PKCS1_OAEP_PADDING, oaepHash: 'sha256' }, Buffer.from(stub.key, 'base64'));
  const iv = Buffer.from(stub.iv, 'base64');
  const data = Buffer.from(stub.data, 'base64');
  const d = crypto.createDecipheriv('aes-256-gcm', aesKey, iv, { authTagLength: 16 });
  d.setAuthTag(data.subarray(data.length - 16));
  const text = Buffer.concat([d.update(data.subarray(0, data.length - 16)), d.final()]).toString('utf8');
  return { aesKey, iv, text };
}
async function decryptWeb(stub) {
  const raw = await subtle.decrypt({ name: 'RSA-OAEP' }, webPrivateKey, Buffer.from(stub.key, 'base64'));
  const k = await subtle.importKey('raw', raw, { name: 'AES-GCM' }, false, ['decrypt']);
  const plain = await subtle.decrypt({ name: 'AES-GCM', iv: Buffer.from(stub.iv, 'base64') }, k, Buffer.from(stub.data, 'base64'));
  return new TextDecoder().decode(plain);
}

/** Strict check of the file text; returns the parsed stub or null. */
function checkStubText(text, label) {
  const lines = text.split('\n');
  ok(lines.length === 3 && lines[2] === '', label + ': two lines ending with a newline');
  ok(lines[0] === COMMENT, label + ': first line is the generated comment');
  const m = /^SATLibrary\.registerPremium\((\{.*\})\);$/.exec(lines[1] || '');
  if (!ok(!!m, label + ': second line is SATLibrary.registerPremium({...});')) return null;
  const stub = JSON.parse(m[1]);
  eq(Object.keys(stub), KEYS, label + ': JSON keys and order');
  ok(stub.v === 1 && (['advanced', 'topic', 'challenge', ''].includes(stub.section)) && typeof stub.date === 'string' && stub.kid === repoPub.kid, label + ': v / section / date / kid');
  ok([stub.key, stub.iv, stub.data].every((s) => /^[A-Za-z0-9+/]*={0,2}$/.test(s) && s.length % 4 === 0), label + ': standard base64 with padding');
  ok(Buffer.from(stub.key, 'base64').length === 256 && Buffer.from(stub.iv, 'base64').length === 12, label + ': wrapped key 256 bytes, IV 12 bytes');
  return stub;
}


function runCheck(root, out) {
  const problems = [];
  let pub = null;
  try { pub = loadPublicKey(root); } catch (e) { problems.push(e.message); }
  const site = loadSite(root);
  const s = scan(root, site, pub);
  problems.push(...s.problems);
  for (const p of s.plans) problems.push('tests/' + p.file + ': plaintext Premium test (must be encrypted: run node tools/premium/encrypt.mjs)');
  for (const [file, st] of s.stubs) {
    if (st.problems.length && !st.reported) problems.push('tests/' + file + ': malformed encrypted file (' + st.problems.join('; ') + ')');
  }
  for (const f of findPrivateKeys(root)) {
    problems.push(f + ': looks like a PRIVATE key. Remove it from the repository now; if it was ever pushed, it is public: make a new key pair.');
  }
  const listedPremium = new Set();
  for (const e of s.manifest.entries) {
    if (!e.file.startsWith(PREMIUM_DIR + '/')) continue;
    if (listedPremium.has(e.file)) problems.push('tests/manifest.js: lists ' + e.file + ' twice');
    listedPremium.add(e.file);
    if (!s.stubs.has(e.file)) problems.push('tests/manifest.js: lists ' + e.file + ' but tests/' + e.file + ' does not exist');
  }
  for (const r of s.repairs) problems.push('tests/manifest.js: lists ' + r.file + ' (missing) instead of ' + r.premiumFile + ' (run node tools/premium/encrypt.mjs)');
  // A listed plaintext test and a listed encrypted test with the same id would clash on the site
  const stubIds = new Map();
  for (const file of listedPremium) {
    const st = s.stubs.get(file);
    if (!st || !st.stub || typeof st.stub.id !== 'string') continue;
    if (stubIds.has(st.stub.id)) problems.push('tests/' + file + ' and tests/' + stubIds.get(st.stub.id) + ' have the same test id "' + st.stub.id + '"');
    else stubIds.set(st.stub.id, file);
  }
  for (const t of s.tests) {
    if (t.listed && !t.premium && stubIds.has(t.id)) problems.push('tests/' + t.file + ' and tests/' + stubIds.get(t.id) + ' are both listed with the test id "' + t.id + '"');
  }
  if (problems.length) {
    out.error('Premium check FAILED:');
    problems.forEach((p) => out.error('  - ' + p));
    return 1;
  }
  out.log('Premium check OK: ' + s.stubs.size + ' encrypted test(s), no plaintext Premium tests, no private keys.');
  return 0;
}

function runEncrypt(root, dryRun, out) {
  const pub = loadPublicKey(root);
  const site = loadSite(root);
  site.notes.forEach((n) => out.error('note: ' + n));
  const s = scan(root, site, pub);
  s.notes.forEach((n) => out.error('note: ' + n));
  const would = dryRun ? 'would ' : '';

  // Problems block only the files they concern; everything else is still encrypted.
  const plans = s.plans.filter((p) => !p.blocked);

  // 1) Encrypt everything in memory first (and check the result), so a failure here writes nothing.
  const writes = [];
  for (const p of plans) {
    const existed = fs.existsSync(p.premiumAbs);
    out.log(would + (existed ? 're-encrypt' : 'encrypt') + ' tests/' + p.file + ' -> tests/' + p.premiumFile +
      ' ("' + p.meta.title + '", ' + p.meta.questionCount + ' questions' + (p.listed ? '' : ', not listed in tests/manifest.js') + ')');
    p.warnings.forEach((w) => out.error('  warning: ' + w));
    if (dryRun) continue;
    const text = stubText(p.meta, encryptText(p.json, pub), pub.kid);
    const chk = parseStub(text, pub);
    if (chk.problems.length) throw new Error('Internal error: generated file for tests/' + p.file + ' is invalid: ' + chk.problems.join('; ') + '. Nothing was written.');
    writes.push({ file: p.premiumAbs, text });
  }

  // 2) Manifest
  let manifestChanged = false;
  if (s.manifest.exists) {
    const entries = nextManifest(s.manifest.entries, plans, s.repairs);
    const changed = JSON.stringify(entries) !== JSON.stringify(s.manifest.entries);
    if (changed) {
      manifestChanged = true;
      s.repairs.forEach((r) => out.log(would + 'list ' + r.premiumFile + ' instead of ' + r.file + ' in tests/manifest.js'));
      out.log(would + 'update tests/manifest.js');
      writes.push({ file: path.join(root, 'tests', 'manifest.js'), text: manifestText(entries) });
    }
  }

  // 3) Write the encrypted files and the manifest together, then delete the plaintext (only after that succeeded)
  if (!dryRun) writeFilesAtomic(writes);
  for (const p of plans) {
    if (p.abs === p.premiumAbs) continue; // encrypted in place
    out.log(would + 'delete tests/' + p.file);
    if (!dryRun) fs.unlinkSync(p.abs);
  }

  if (s.problems.length) {
    out.error('Some files need attention:');
    s.problems.forEach((p) => out.error('  - ' + p));
  }
  if (!plans.length && !manifestChanged) {
    out.log(s.problems.length ? 'Nothing was encrypted.' : 'Nothing to encrypt: no plaintext Premium tests.');
  } else if (dryRun) {
    out.log('Dry run: ' + plans.length + ' test(s) would be encrypted' + (manifestChanged ? ' and tests/manifest.js updated' : '') + '; nothing was written.');
  } else {
    out.log((plans.length ? 'Encrypted ' + plans.length + ' test(s).' : 'Updated tests/manifest.js.') +
      ' Commit tests/premium/, tests/manifest.js' + (plans.length ? ' and the deleted plaintext files' : '') + ' together.');
  }
  return s.problems.length ? 1 : 0;
}

/* ---------------- CLI ---------------- */

const USAGE = [
  'Usage: node tools/premium/encrypt.mjs [--root <dir>] [--check | --dry-run]',
  '',
  '  (no option)  encrypt every plaintext Premium test (section: advanced, or premium: yes) anywhere in tests/ into tests/premium/,',
  '               delete the plaintext file and update tests/manifest.js',
  '  --check      exit 1 if a plaintext Premium test exists, an encrypted file is broken/out of date,',
  '               or a file in the repository looks like a private key',
  '  --dry-run    show what would change without writing anything',
  '  --root <dir> site folder (default: the repository that contains this script)'
].join('\n');

export function parseArgs(argv) {
  const opts = { root: null, check: false, dryRun: false, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--check') opts.check = true;
    else if (a === '--dry-run' || a === '-n') opts.dryRun = true;
    else if (a === '--help' || a === '-h') opts.help = true;
    else if (a === '--root') {
      if (i + 1 >= argv.length) throw new UsageError('--root needs a folder.');
      opts.root = argv[++i];
    } else if (a.startsWith('--root=')) opts.root = a.slice(7);
    else throw new UsageError('Unknown option: ' + a);
  }
  if (opts.check && opts.dryRun) throw new UsageError('Use either --check or --dry-run, not both.');
  return opts;
}

export function main(argv, out = console) {
  let opts;
  try { opts = parseArgs(argv); } catch (e) { out.error(e.message + '\n\n' + USAGE); return 2; }
  if (opts.help) { out.log(USAGE); return 0; }
  const here = path.dirname(fileURLToPath(import.meta.url));
  const root = path.resolve(opts.root || path.join(here, '..', '..'));
  if (!fs.existsSync(path.join(root, 'tests')) || !fs.statSync(path.join(root, 'tests')).isDirectory()) {
    out.error('No tests/ folder in ' + root + ' (use --root <site folder>).');
    return 2;
  }
  try {
    return opts.check ? runCheck(root, out) : runEncrypt(root, opts.dryRun, out);
  } catch (e) {
    out.error('Error: ' + (e && e.message || e));
    return e instanceof UsageError ? 2 : 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}

#!/usr/bin/env node
/*
 * tunn.sat Premium — encrypts Premium tests so they can be committed to the public repository. Premium tests are
 * the Advanced tests (section: advanced) and every test marked "premium: yes" (Practice, Topic or Elite).
 *
 *   node tools/premium/encrypt.mjs [--root <dir>]   encrypt every plaintext Premium test
 *                                                  anywhere in tests/ into tests/premium/<name>.js, delete the
 *                                                  plaintext file and update tests/manifest.js
 *   node tools/premium/encrypt.mjs --check         exit 1 (listing the files) if a plaintext Premium test exists,
 *                                                  a test not marked Premium has the id or file name of an encrypted
 *                                                  test (a public copy of paid content), an encrypted file is broken /
 *                                                  out of date with the manifest, or a file in the repository looks
 *                                                  like a PRIVATE key
 *   node tools/premium/encrypt.mjs --dry-run       show what would change, write nothing
 *
 * Needs only Node >= 18 built-ins and the PUBLIC key (assets/premium-key.json). Encryption is one-way here: keep your
 * own copy of a test's text if you want to edit it later (only the owner's private key, which is never in the
 * repository, can decrypt it; see tools/premium/decrypt.mjs).
 * File format and crypto: see the Premium spec (README "Premium" section and tools/premium/HUONG-DAN.md).
 *
 * Writes are all-or-nothing: every encrypted file and the manifest are first written to temporary files, then
 * renamed into place, and only then are the plaintext files deleted. Files with problems are left untouched.
 *
 * Exit codes: 0 = OK, 1 = problems found (listed on stderr), 2 = usage or setup error.
 * Test files are executed with node:vm to read them, like the browser does; node:vm is not a security sandbox,
 * so only run this on the site's own repository.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const STUB_COMMENT = '/* tunn.sat Premium test (encrypted). Generated by tools/premium/encrypt.mjs; do not edit by hand. */';
/** Sections a Premium stub keeps (Advanced, Topic, Elite); '' is a Premium Practice Test. */
export const PREMIUM_SECTIONS = ['advanced', 'topic', 'challenge'];

export const STUB_KEYS = ['v', 'id', 'title', 'category', 'description', 'section', 'date', 'questionCount', 'mcqCount',
  'sprCount', 'totalTime', 'moduleCount', 'kid', 'key', 'iv', 'data'];
const LEGACY_STUB_KEYS = STUB_KEYS.filter((k) => k !== 'date');
const STUB_LINE = /^SATLibrary\.registerPremium\((\{.*\})\);$/;
const PREMIUM_DIR = 'premium';
const VM_TIMEOUT = 10000;
// U+2028 / U+2029 are escaped in the JSON so old browsers can parse the file.
const LINE_SEP = new RegExp(String.fromCharCode(0x2028), 'g');
const PARA_SEP = new RegExp(String.fromCharCode(0x2029), 'g');
// Same values as normalizeSection() in assets/js/parser.js, as a front-matter line (section: advanced) or a JSON /
// JS object property ("section": "advanced", section: 'adv'). Only used for files the site's parser cannot read
// (syntax errors, other file types), so it errs on the side of flagging.
export const LOOKS_ADVANCED = /(?:^|[\s{,;(])["'`]?(?:section|phần)["'`]?\s*[:：]\s*["'`]?\s*(?:advanced|adv|nâng cao|nang cao)\b/im;
// Same values as normalizePremium() in assets/js/parser.js ("premium: yes", "premium": true, …).
// (\b only knows ASCII letters, so the end of the value is "not followed by a letter or digit" in Unicode: "có")
export const LOOKS_PREMIUM_FLAG = /(?:^|[\s{,;(])["'`]?(?:premium|trả phí|tra phi)["'`]?\s*[:：]\s*["'`]?\s*(?:yes|y|true|1|on|có|co|premium)(?![\p{L}\p{N}_])/imu;
export function looksPremium(text) { return LOOKS_ADVANCED.test(text) || LOOKS_PREMIUM_FLAG.test(text); }
// Private keys must never be in the repository (only the PUBLIC key, assets/premium-key.json).
const PEM_PRIVATE = /-----BEGIN (?:[A-Z0-9]+ )*PRIVATE KEY-----\s*[A-Za-z0-9+/=\r\n]{64,}/;
const JWK_PRIVATE_D = /["']?\bd["']?\s*:\s*["'`][A-Za-z0-9_-]{40,}={0,2}["'`]/;
const MAX_SCAN_BYTES = 5 * 1024 * 1024;

class UsageError extends Error {}

/* ---------------- Small helpers ---------------- */

const quietConsole = { log() {}, info() {}, warn() {}, error() {}, debug() {} };

function rel(root, abs) {
  return path.relative(root, abs).split(path.sep).join('/');
}

function isStrictBase64(s) {
  return typeof s === 'string' && s.length % 4 === 0 && /^[A-Za-z0-9+/]*={0,2}$/.test(s) &&
    Buffer.from(s, 'base64').toString('base64') === s;
}

/** Same as safeId() in assets/js/store.js. */
export function safeId(id) {
  return String(id || '').replace(/[^a-zA-Z0-9_-]/g, '-').replace(/-{2,}/g, '-').replace(/^-+|-+$/g, '').slice(0, 80);
}

/** Manifest "v" after a change: integer + 1, otherwise '1'. Several versions (merged entries): max + 1. */
export function bumpVersion(...versions) {
  const nums = versions.filter((v) => /^\d+$/.test(String(v == null ? '' : v))).map((v) => BigInt(v));
  if (!nums.length) return '1';
  return String(nums.reduce((a, b) => (b > a ? b : a)) + 1n);
}

/**
 * Writes several files all-or-nothing (as far as the file system allows): every file is first written to a
 * temporary file next to its target; if any of those writes fails, the temporary files are removed and nothing
 * changed. Then they are renamed into place.
 */
function writeFilesAtomic(list) {
  const staged = [];
  let current = '';
  try {
    for (const { file, text } of list) {
      current = file;
      fs.mkdirSync(path.dirname(file), { recursive: true });
      const tmp = file + '.tmp-' + process.pid + '-' + crypto.randomBytes(4).toString('hex');
      staged.push({ tmp, file });
      fs.writeFileSync(tmp, text, 'utf8');
    }
  } catch (e) {
    staged.forEach((s) => { try { fs.unlinkSync(s.tmp); } catch (e2) { /* not created */ } });
    throw new Error('Could not write ' + (current || 'the files') + ' (' + (e && e.message || e) + '); nothing was changed.');
  }
  for (const s of staged) fs.renameSync(s.tmp, s.file);
}

/** Every entry under dir (paths relative to base, '/'-separated), sorted by name; symbolic links are not followed. */
function listFiles(dir, base = dir, out = []) {
  const ents = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const ent of ents) {
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) listFiles(abs, base, out);
    else out.push({ file: rel(base, abs), abs, isFile: ent.isFile() });
  }
  return out;
}

/** The start of a file as text, or null for a binary / unreadable file. */
function readText(abs) {
  let buf;
  try {
    const fd = fs.openSync(abs, 'r');
    try {
      buf = Buffer.alloc(Math.min(fs.fstatSync(fd).size, MAX_SCAN_BYTES));
      buf = buf.subarray(0, fs.readSync(fd, buf, 0, buf.length, 0));
    } finally { fs.closeSync(fd); }
  } catch (e) { return null; }
  if (buf.subarray(0, 8000).includes(0)) return null;
  return buf.toString('utf8');
}

/** True if a text looks like a private key (PEM, or a JWK with a "d" member). */
export function looksLikePrivateKey(text) {
  return PEM_PRIVATE.test(text) || (/["']?kty["']?\s*:/.test(text) && JWK_PRIVATE_D.test(text));
}

/**
 * Files of the repository (what `git add -A` would commit: tracked + untracked, not ignored) that look like a
 * private key. Without git (e.g. a copy of the site), every file except .git/ and node_modules/ is checked.
 */
export function findPrivateKeys(root) {
  let files = null;
  const g = spawnSync('git', ['-C', root, 'ls-files', '-z', '--cached', '--others', '--exclude-standard'], { encoding: 'utf8' });
  if (!g.error && g.status === 0) files = g.stdout.split('\0').filter(Boolean);
  if (!files) {
    files = [];
    const walk = (dir) => {
      for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        if (ent.name === '.git' || ent.name === 'node_modules') continue;
        const abs = path.join(dir, ent.name);
        if (ent.isDirectory()) walk(abs);
        else if (ent.isFile()) files.push(rel(root, abs));
      }
    };
    walk(root);
  }
  const found = [];
  for (const f of files.sort()) {
    const abs = path.join(root, f);
    let st;
    try { st = fs.lstatSync(abs); } catch (e) { continue; } // deleted in the work tree
    if (!st.isFile()) continue;
    const text = readText(abs);
    if (text != null && looksLikePrivateKey(text)) found.push(f.split(path.sep).join('/'));
  }
  return found;
}

/* ---------------- Manifest (same format as manifestText() in assets/js/admin.js) ---------------- */

export function manifestText(entries) {
  return '/*\n' +
    ' * Published practice tests. The site sorts them by test date, so order does not matter.\n' +
    ' * This file is updated by the admin page (#/admin) and can also be edited by hand.\n' +
    ' * Each entry: { file: \'name.js\', v: \'version\' } — "v" changes on every publish so browsers fetch the new file.\n' +
    ' */\n' +
    'SATLibrary.manifest([\n' +
    entries.map((e) => '  { file: ' + JSON.stringify(e.file).replace(/"/g, '\'') + ', v: ' + JSON.stringify(e.v || '1').replace(/"/g, '\'') + ' }').join(',\n') +
    '\n]);\n';
}

/** Same as normalizeEntry() in assets/js/store.js. */
function normalizeEntry(e) {
  if (!e) return null;
  if (typeof e === 'string') return { file: e, v: '' };
  if (typeof e === 'object' && e.file) return { file: String(e.file), v: e.v != null ? String(e.v) : '' };
  return null;
}

function cleanFile(file) {
  return String(file).replace(/\\/g, '/').replace(/^(\.\/)+/, '');
}

/** Runs tests/manifest.js like the site does and returns its entries. */
function readManifest(root) {
  const file = path.join(root, 'tests', 'manifest.js');
  if (!fs.existsSync(file)) return { exists: false, text: '', entries: [] };
  const text = fs.readFileSync(file, 'utf8');
  let calls = 0;
  let entries = [];
  const sandbox = {
    console: quietConsole,
    SATLibrary: {
      manifest(list) { calls++; entries = (Array.isArray(list) ? Array.from(list) : []).map(normalizeEntry).filter(Boolean); },
      register() {}, registerPremium() {}
    }
  };
  const ctx = vm.createContext(sandbox);
  try {
    vm.runInContext('var window = globalThis, self = globalThis;', ctx);
    vm.runInContext(text, ctx, { filename: 'tests/manifest.js', timeout: VM_TIMEOUT });
  } catch (e) {
    throw new Error('Could not read tests/manifest.js: ' + (e && e.message || e));
  }
  if (calls !== 1) throw new Error('tests/manifest.js must call SATLibrary.manifest([...]) exactly once (found ' + calls + ').');
  return { exists: true, text, entries: entries.map((e) => ({ file: cleanFile(e.file), v: e.v })) };
}

/* ---------------- The site's parser (assets/js/parser.js) ---------------- */

/**
 * Loads config.js, grading.js and parser.js into a sandbox, like index.html does, and returns
 * { P, minutesPerQuestion, notes }.
 */
export function loadSite(root) {
  const ctx = vm.createContext({ console: quietConsole });
  vm.runInContext('var window = globalThis, self = globalThis;', ctx);
  const notes = [];
  const run = (relPath, required) => {
    const file = path.join(root, relPath);
    if (!fs.existsSync(file)) {
      if (required) throw new UsageError('Missing ' + relPath + ' (is --root the site folder?).');
      notes.push(relPath + ' not found');
      return;
    }
    try {
      vm.runInContext(fs.readFileSync(file, 'utf8'), ctx, { filename: relPath, timeout: VM_TIMEOUT });
    } catch (e) {
      if (required) throw new Error('Could not load ' + relPath + ': ' + (e && e.message || e));
      notes.push('could not load ' + relPath + ' (' + (e && e.message || e) + ')');
    }
  };
  run('assets/js/config.js', false);
  run('assets/js/grading.js', false);
  run('assets/js/parser.js', true);
  const P = ctx.P;
  if (!P || typeof P.parseText !== 'function' || typeof P.normalizeObject !== 'function') {
    throw new Error('assets/js/parser.js did not define P.parseText / P.normalizeObject.');
  }
  const cfg = ctx.APP_CONFIG || {};
  const minutesPerQuestion = Number(cfg.defaultMinutesPerQuestion) || 1.6;
  return { P, minutesPerQuestion, notes };
}

/**
 * Parses a test definition (what a file passes to SATLibrary.register) with the site's parser and applies
 * the rules of prepare() in assets/js/store.js. `def` must already be a JSON round-trip (what the browser
 * gets back after decryption).
 */
export function analyze(site, def) {
  const res = typeof def === 'string' ? site.P.parseText(def) : site.P.normalizeObject(def);
  if (!res || !res.test) {
    return { test: null, errors: (res && res.errors) || [{ msg: 'Invalid test data.' }], warnings: [] };
  }
  const t = res.test;
  // prepare(): drop empty modules, default module time, totals
  const modules = (t.modules || []).filter((m) => m.questions && m.questions.length);
  let questionCount = 0, mcqCount = 0, sprCount = 0, totalTime = 0;
  modules.forEach((m) => {
    m.questions.forEach((q) => { questionCount++; if (q.type === 'mcq') mcqCount++; else sprCount++; });
    let time = m.time;
    if (time == null || !isFinite(time) || time <= 0) time = Math.max(5, Math.round(m.questions.length * site.minutesPerQuestion));
    totalTime += time || 0;
  });
  return {
    test: {
      id: safeId(t.id),
      title: String(t.title || ''),
      category: String(t.category || ''),
      description: String(t.description || ''),
      section: String(t.section || ''),
      date: String(t.date || ''),
      // Premium: every Advanced test, and Practice Tests marked "premium: yes" (P.isPremium in parser.js)
      premium: t.section === 'advanced' || t.premium === true,
      questionCount, mcqCount, sprCount, totalTime,
      moduleCount: modules.length
    },
    errors: Array.from(res.errors || []),
    warnings: Array.from(res.warnings || [])
  };
}

/* ---------------- Test files ---------------- */

/** Runs a file from tests/ in a sandbox and returns what it passed to SATLibrary.register / registerPremium. */
function runTestFile(root, abs) {
  const code = fs.readFileSync(abs, 'utf8');
  const defs = [], stubs = [];
  const sandbox = {
    console: quietConsole,
    SATLibrary: {
      register(def) { defs.push(def); },
      registerPremium(stub) { stubs.push(stub); },
      manifest() {}
    }
  };
  const ctx = vm.createContext(sandbox);
  vm.runInContext('var window = globalThis, self = globalThis;', ctx);
  vm.runInContext(code, ctx, { filename: rel(root, abs), timeout: VM_TIMEOUT });
  return { code, defs, stubs };
}

/**
 * Validates the text of a tests/premium/*.js file. Returns { stub, problems: [] }.
 * pub (optional): the public key, to check the wrapped key length.
 */
export function parseStub(text, pub) {
  const problems = [];
  const lines = String(text).replace(/\r\n/g, '\n').split('\n'); // tolerate a CRLF checkout (Windows)
  if (lines.length !== 3 || lines[2] !== '') problems.push('must be exactly two lines ending with a newline');
  if (lines[0] !== STUB_COMMENT) problems.push('first line is not the generated comment');
  const m = STUB_LINE.exec(lines[1] || '');
  if (!m) { problems.push('second line is not SATLibrary.registerPremium({...});'); return { stub: null, problems }; }
  let stub;
  try { stub = JSON.parse(m[1]); } catch (e) { problems.push('invalid JSON (' + e.message + ')'); return { stub: null, problems }; }
  if (!stub || typeof stub !== 'object' || Array.isArray(stub)) { problems.push('not a JSON object'); return { stub: null, problems }; }
  const keys = Object.keys(stub);
  // Files written before "date" was added (Advanced tests only) are still valid: the site reads them as before
  const legacy = keys.join(',') === LEGACY_STUB_KEYS.join(',');
  if (!legacy && keys.join(',') !== STUB_KEYS.join(',')) problems.push('keys must be exactly ' + STUB_KEYS.join(', ') + ' (in this order)');
  const isCount = (n) => Number.isInteger(n) && n >= 0;
  if (stub.v !== 1) problems.push('"v" must be 1');
  if (typeof stub.id !== 'string' || !/^[A-Za-z0-9_-]{1,80}$/.test(stub.id) || safeId(stub.id) !== stub.id) problems.push('"id" is not a valid test id');
  ['title', 'category', 'description'].forEach((k) => { if (typeof stub[k] !== 'string') problems.push('"' + k + '" must be a string'); });
  if (legacy ? stub.section !== 'advanced' : !PREMIUM_SECTIONS.includes(stub.section) && stub.section !== '') problems.push('"section" must be "advanced", "topic", "challenge" or "" (a Premium Practice Test)');
  if (!legacy && (typeof stub.date !== 'string' || stub.date.length > 1000)) problems.push('"date" must be a string');
  ['questionCount', 'mcqCount', 'sprCount', 'moduleCount'].forEach((k) => { if (!isCount(stub[k])) problems.push('"' + k + '" must be a whole number'); });
  if (isCount(stub.questionCount) && isCount(stub.mcqCount) && isCount(stub.sprCount) && stub.questionCount !== stub.mcqCount + stub.sprCount) {
    problems.push('"questionCount" is not mcqCount + sprCount');
  }
  if (typeof stub.totalTime !== 'number' || !isFinite(stub.totalTime) || stub.totalTime < 0) problems.push('"totalTime" must be a number of minutes');
  if (typeof stub.kid !== 'string' || !/^[A-Za-z0-9_.-]{1,64}$/.test(stub.kid)) problems.push('"kid" is not a valid key id');
  if (!isStrictBase64(stub.key) || stub.key.length > 1024) problems.push('"key" is not standard base64 (at most 1024 characters)');
  else if (pub && stub.kid === pub.kid && Buffer.from(stub.key, 'base64').length !== pub.modulusBytes) problems.push('"key" has the wrong length for key ' + pub.kid);
  else if (Buffer.from(stub.key, 'base64').length < 128) problems.push('"key" is too short');
  if (!isStrictBase64(stub.iv) || Buffer.from(stub.iv, 'base64').length !== 12) problems.push('"iv" must be 12 bytes of standard base64');
  if (!isStrictBase64(stub.data) || Buffer.from(stub.data, 'base64').length < 18) problems.push('"data" is not standard base64 AES-GCM ciphertext');
  return { stub, problems };
}

/** Full check of a stub file: text format + it really calls registerPremium with that object. */
function checkStubFile(root, abs, pub) {
  const text = fs.readFileSync(abs, 'utf8');
  const res = parseStub(text, pub);
  if (res.stub && !res.problems.length) {
    try {
      const ran = runTestFile(root, abs);
      if (ran.stubs.length !== 1 || ran.defs.length) res.problems.push('does not call SATLibrary.registerPremium exactly once');
      else if (JSON.stringify(ran.stubs[0]) !== JSON.stringify(res.stub)) res.problems.push('registers a different object than its JSON');
    } catch (e) {
      res.problems.push('cannot run (' + (e && e.message || e) + ')');
    }
  }
  return res;
}

/* ---------------- Crypto ---------------- */

export function loadPublicKey(root) {
  const file = path.join(root, 'assets', 'premium-key.json');
  if (!fs.existsSync(file)) throw new UsageError('Missing assets/premium-key.json (the Premium public key).');
  let j;
  try { j = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) { throw new UsageError('assets/premium-key.json is not valid JSON: ' + e.message); }
  if (!j || typeof j.kid !== 'string' || !/^[A-Za-z0-9_.-]{1,64}$/.test(j.kid)) throw new UsageError('assets/premium-key.json: missing or invalid "kid".');
  if (j.alg !== 'RSA-OAEP-256') throw new UsageError('assets/premium-key.json: "alg" must be "RSA-OAEP-256".');
  if (typeof j.spki !== 'string' || !isStrictBase64(j.spki)) throw new UsageError('assets/premium-key.json: "spki" must be standard base64.');
  if (j.d || j.p || j.q || j.private || /PRIVATE/.test(JSON.stringify(j))) {
    throw new UsageError('assets/premium-key.json looks like it contains a PRIVATE key. Remove it from the repository now; only the public key belongs there.');
  }
  let keyObject;
  try { keyObject = crypto.createPublicKey({ key: Buffer.from(j.spki, 'base64'), format: 'der', type: 'spki' }); } catch (e) {
    throw new UsageError('assets/premium-key.json: "spki" is not a valid public key (' + e.message + ').');
  }
  const details = keyObject.asymmetricKeyDetails || {};
  if (keyObject.asymmetricKeyType !== 'rsa' || !(details.modulusLength >= 2048)) throw new UsageError('assets/premium-key.json: the key must be RSA with at least 2048 bits.');
  return { kid: j.kid, keyObject, modulusBytes: Math.ceil(details.modulusLength / 8) };
}

/** AES-256-GCM with a fresh random key and IV; the key is wrapped with RSA-OAEP (SHA-256). */
export function encryptText(plaintext, pub) {
  const data = Buffer.from(plaintext, 'utf8');
  const aesKey = crypto.randomBytes(32);
  const iv = crypto.randomBytes(12);
  try {
    const cipher = crypto.createCipheriv('aes-256-gcm', aesKey, iv, { authTagLength: 16 });
    const ct = Buffer.concat([cipher.update(data), cipher.final(), cipher.getAuthTag()]); // WebCrypto layout: ciphertext || tag
    // Self-check before the plaintext is deleted.
    const decipher = crypto.createDecipheriv('aes-256-gcm', aesKey, iv, { authTagLength: 16 });
    decipher.setAuthTag(ct.subarray(ct.length - 16));
    const back = Buffer.concat([decipher.update(ct.subarray(0, ct.length - 16)), decipher.final()]);
    if (!back.equals(data)) throw new Error('AES self-check failed');
    const wrapped = crypto.publicEncrypt({ key: pub.keyObject, padding: crypto.constants.RSA_PKCS1_OAEP_PADDING, oaepHash: 'sha256' }, aesKey);
    if (wrapped.length !== pub.modulusBytes) throw new Error('RSA-OAEP produced ' + wrapped.length + ' bytes');
    return { key: wrapped.toString('base64'), iv: iv.toString('base64'), data: ct.toString('base64') };
  } finally {
    aesKey.fill(0);
  }
}

export function stubText(meta, enc, kid) {
  const obj = {
    v: 1, id: meta.id, title: meta.title, category: meta.category, description: meta.description,
    section: PREMIUM_SECTIONS.includes(meta.section) ? meta.section : '', date: meta.date || '',
    questionCount: meta.questionCount, mcqCount: meta.mcqCount, sprCount: meta.sprCount, totalTime: meta.totalTime,
    moduleCount: meta.moduleCount, kid, key: enc.key, iv: enc.iv, data: enc.data
  };
  const json = JSON.stringify(obj).replace(LINE_SEP, '\\u2028').replace(PARA_SEP, '\\u2029');
  return STUB_COMMENT + '\n' + 'SATLibrary.registerPremium(' + json + ');\n';
}

/* ---------------- Scan ---------------- */

/**
 * Looks at tests/ and the manifest. Returns
 * { manifest, plans: [{ file, abs, premiumFile, premiumAbs, def, json, meta, warnings }], repairs, problems, stubs }
 * where problems are hard errors (the run exits 1) and file paths are relative to tests/.
 */
function scan(root, site, pub) {
  const testsDir = path.join(root, 'tests');
  const manifest = readManifest(root);
  const problems = [];
  const notes = [];
  const plans = [];

  // Existing encrypted files: tests/premium/*.js
  const premiumDir = path.join(testsDir, PREMIUM_DIR);
  const isStubPath = (file) => file.startsWith(PREMIUM_DIR + '/') && file.endsWith('.js') && file.indexOf('/', PREMIUM_DIR.length + 1) === -1;
  const allFiles = listFiles(testsDir);
  const stubs = new Map(); // 'premium/x.js' -> { stub, problems }
  const listed = manifest.entries.map((e) => e.file);
  const candidates = [];
  const seen = new Set();
  for (const f of allFiles) {
    if (!isStubPath(f.file)) continue;
    if (!f.isFile) { problems.push('tests/' + f.file + ': is not a regular file.'); continue; }
    const st = checkStubFile(root, f.abs, pub);
    stubs.set(f.file, st);
    // A plaintext test saved straight into tests/premium/ by mistake: encrypt it in place.
    if (st.problems.length) {
      let ran = null;
      try { ran = runTestFile(root, f.abs); } catch (e) { ran = null; }
      if (ran && ran.defs.length) { seen.add(f.file); candidates.push({ file: f.file, listed: listed.includes(f.file) }); }
      else st.reported = true;
    }
  }
  for (const [file, st] of stubs) {
    if (st.reported) problems.push('tests/' + file + ': malformed encrypted file (' + st.problems.join('; ') + ')');
  }

  // Plaintext candidates: listed in the manifest (in order), then every other .js file anywhere under tests/
  for (const file of listed) {
    if (isStubPath(file) || seen.has(file)) continue;
    if (path.isAbsolute(file) || path.normalize(file).split(path.sep).includes('..')) {
      notes.push('tests/manifest.js: ignoring "' + file + '" (outside tests/)');
      continue;
    }
    seen.add(file);
    candidates.push({ file, listed: true });
  }
  for (const f of allFiles) {
    if (f.file === 'manifest.js' || isStubPath(f.file) || seen.has(f.file)) continue;
    if (!f.isFile) { notes.push('tests/' + f.file + ': skipped (not a regular file)'); continue; }
    if (!f.file.endsWith('.js')) {
      // Figures stay public; any other file must not carry a Premium test in plaintext.
      if (f.file.startsWith('images/')) continue;
      const text = readText(f.abs);
      if (text != null && looksPremium(text)) {
        problems.push('tests/' + f.file + ': looks like a Premium test (section: advanced or premium: yes) but is not a .js test file, so it cannot be encrypted. ' +
          'Remove it from tests/ (keep your copy outside the repository), or save it as tests/<name>.js in the test format and run the tool again.');
      }
      continue;
    }
    seen.add(f.file);
    candidates.push({ file: f.file, listed: false });
  }

  const tests = []; // every readable plaintext test: { file, listed, id, premium }
  for (const c of candidates) {
    const abs = path.join(testsDir, c.file);
    let fst;
    try { fst = fs.lstatSync(abs); } catch (e) { continue; } // listed but missing: handled with the repairs below
    if (!fst.isFile()) { notes.push('tests/' + c.file + ': skipped (not a regular file)'); continue; }
    let ran;
    try {
      ran = runTestFile(root, abs);
    } catch (e) {
      const raw = readText(abs) || '';
      const msg = 'tests/' + c.file + ': cannot be read (' + (e && e.message || e) + ')';
      if (looksPremium(raw)) problems.push(msg + ' and it looks like a Premium test, so it was NOT encrypted. Fix the file and run the tool again.');
      else notes.push(msg);
      continue;
    }
    if (!ran.defs.length) {
      if (ran.stubs.length) problems.push('tests/' + c.file + ': encrypted files belong in tests/' + PREMIUM_DIR + '/.');
      else if (c.listed) notes.push('tests/' + c.file + ': does not call SATLibrary.register');
      continue;
    }
    const analyzed = ran.defs.map((def) => {
      if (def == null || (typeof def !== 'object' && typeof def !== 'string')) return { def, json: null, a: null };
      const json = JSON.stringify(def);
      const a = analyze(site, JSON.parse(json));
      return { def, json, a };
    });
    const adv = analyzed.filter((x) => x.a && x.a.test && x.a.test.premium);
    analyzed.forEach((x) => { if (x.a && x.a.test) tests.push({ file: c.file, listed: c.listed, id: x.a.test.id, premium: x.a.test.premium }); });
    if (!adv.length) {
      if (looksPremium(ran.code) && analyzed.some((x) => !x.a || !x.a.test)) {
        problems.push('tests/' + c.file + ': looks like a Premium test but the site cannot parse it, so it was NOT encrypted.');
      }
      continue;
    }
    if (ran.defs.length !== 1) {
      problems.push('tests/' + c.file + ': has ' + ran.defs.length + ' SATLibrary.register calls; a Premium test file must contain exactly one test. It was NOT encrypted.');
      continue;
    }
    const { def, json, a } = adv[0];
    if (!a.test.id) {
      problems.push('tests/' + c.file + ': the test has no id (add id: \'' + path.basename(c.file, '.js') + '\'); it was NOT encrypted.');
      continue;
    }
    const base = path.basename(c.file, '.js');
    const warnings = [];
    if (c.file.startsWith(PREMIUM_DIR + '/')) warnings.push('this plaintext test was in tests/' + PREMIUM_DIR + '/; it is encrypted in place');
    if (a.errors.length) {
      warnings.push('the site reports ' + a.errors.length + ' error(s) in this test and will not show it until they are fixed; first: ' + (a.errors[0].msg || a.errors[0]));
    }
    if (a.test.id !== base) warnings.push('the test id "' + a.test.id + '" differs from the file name "' + base + '"');
    plans.push({
      file: c.file, abs, listed: c.listed, def, json, meta: a.test, warnings,
      premiumFile: PREMIUM_DIR + '/' + base + '.js',
      premiumAbs: path.join(premiumDir, base + '.js')
    });
  }

  // Two plaintext files that would become the same encrypted file
  const byPremium = new Map();
  for (const p of plans) {
    if (byPremium.has(p.premiumFile)) {
      problems.push('tests/' + p.file + ' and tests/' + byPremium.get(p.premiumFile).file + ' would both become tests/' + p.premiumFile + '; neither was encrypted.');
      p.blocked = true;
      byPremium.get(p.premiumFile).blocked = true;
    } else byPremium.set(p.premiumFile, p);
  }
  for (const p of plans) {
    if (p.blocked || p.abs === p.premiumAbs) continue;
    let st = null;
    try { st = fs.lstatSync(p.premiumAbs); } catch (e) { st = null; }
    if (st && !st.isFile()) {
      problems.push('tests/' + p.file + ': tests/' + p.premiumFile + ' exists and is not a regular file, so it was NOT encrypted.');
      p.blocked = true;
    }
  }

  // Test ids must be unique among encrypted tests (the client keys everything by id)
  const idOwner = new Map();
  for (const [file, s] of stubs) {
    if (byPremium.has(file) || !s.stub || typeof s.stub.id !== 'string') continue; // replaced below
    idOwner.set(s.stub.id, 'tests/' + file);
  }
  for (const p of plans) {
    if (p.blocked) continue;
    const other = idOwner.get(p.meta.id);
    if (other) {
      problems.push('tests/' + p.file + ': its test id "' + p.meta.id + '" is already used by ' + other + '; it was NOT encrypted (change the id).');
      p.blocked = true;
    } else idOwner.set(p.meta.id, 'tests/' + p.file);
  }

  // A plaintext test that is not marked Premium but has the id or file name of an encrypted test is a public copy
  // of paid content (for example a source file saved without "premium: yes").
  const stubIdFiles = new Map();
  const stubBases = new Map();
  for (const [file, s] of stubs) {
    if (s.stub && typeof s.stub.id === 'string') stubIdFiles.set(s.stub.id, file);
    stubBases.set(path.basename(file, '.js'), file);
  }
  for (const t of tests) {
    if (t.premium) continue;
    const other = stubIdFiles.get(t.id) || stubBases.get(path.basename(t.file, '.js'));
    if (other && other !== t.file) {
      problems.push('tests/' + t.file + ': plaintext copy of the encrypted Premium test tests/' + other + ' (same id or file name). ' +
        'Delete it from the repository (keep your copy outside it), or add "premium: yes" and run the tool to encrypt it.');
    }
  }

  // Listed plaintext files that are gone because they are already encrypted (manifest not updated)
  const repairs = [];
  for (const e of manifest.entries) {
    if (e.file.startsWith(PREMIUM_DIR + '/')) continue;
    const premiumFile = PREMIUM_DIR + '/' + path.basename(e.file, '.js') + '.js';
    if (!fs.existsSync(path.join(testsDir, e.file)) && stubs.has(premiumFile) && !repairs.some((r) => r.file === e.file)) {
      repairs.push({ file: e.file, premiumFile });
    }
  }

  return { manifest, plans, repairs, problems, notes, stubs, tests };
}

/** Applies plans and repairs to the manifest entries (positions kept). Returns the new entries. */
function nextManifest(entries, plans, repairs) {
  let out = entries.map((e) => ({ file: e.file, v: e.v }));
  const replace = (plainFile, premiumFile) => {
    if (plainFile === premiumFile) { // encrypted in place
      const i = out.findIndex((e) => e.file === premiumFile);
      if (i >= 0) out[i] = { file: premiumFile, v: bumpVersion(out[i].v) };
      return;
    }
    const iPlain = out.findIndex((e) => e.file === plainFile);
    const iPrem = out.findIndex((e) => e.file === premiumFile);
    if (iPlain >= 0) {
      const versions = [out[iPlain].v].concat(iPrem >= 0 ? [out[iPrem].v] : []);
      out[iPlain] = { file: premiumFile, v: bumpVersion(...versions) };
      out = out.filter((e, i) => !(e.file === plainFile) && !(i !== iPlain && e.file === premiumFile));
    } else if (iPrem >= 0) {
      out[iPrem] = { file: premiumFile, v: bumpVersion(out[iPrem].v) };
    }
  };
  plans.forEach((p) => replace(p.file, p.premiumFile));
  repairs.forEach((r) => replace(r.file, r.premiumFile));
  return out;
}

